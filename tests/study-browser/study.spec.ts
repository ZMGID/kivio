test('Study embeds one real Chat composer and preserves normal Chat and per-page draft isolation', async ({ page }, info) => {
  await page.getByRole('button', { name: 'Normal Chat', exact: true }).click()
  const normal = page.locator('[data-composer-presentation="chat"] .chat-composer-editor[role="textbox"]')
  await expect(normal).toBeVisible()
  await normal.fill('Ordinary Chat draft must stay ordinary')
  await page.getByRole('button', { name: 'Study', exact: true }).click()
  const id = await importMaterial(page, material())
  await expectSharedChat(page)
  await expect(editor(page)).toHaveText('')
  await expect(editor(page)).toHaveAttribute('contenteditable', 'true')
  await editor(page).fill('Reading page one draft')
  await jumpToPage(page, 2)
  await editor(page).fill('Reading page two draft')
  await page.getByRole('button', { name: 'Normal Chat', exact: true }).click()
  await expect(normal).toHaveText('Ordinary Chat draft must stay ordinary')
  await expect(page.locator('[data-chat-composer="true"]')).toHaveCount(1)
  await expect(page.locator('[data-composer-presentation="reading"]')).toHaveCount(0)
  await normal.press('Enter')
  await expect.poll(() => page.evaluate(() => window.__studyTest.requests.length)).toBe(1)
  const ordinary = await page.evaluate(() => window.__studyTest.requests[0])
  expect(ordinary.studySource).toBeUndefined()
  expect(ordinary.attachments).toHaveLength(0)
  await expect.poll(async () => (await savedConversations(page)).find(item => item.id === ordinary.conversationId)?.messages.at(-1)?.stream_outcome).toBe('completed')
  await page.getByRole('button', { name: 'Study', exact: true }).click()
  await expectSharedChat(page)
  await expect(editor(page)).toHaveText('Reading page two draft')
  await jumpToPage(page, 1)
  await expect(editor(page)).toHaveText('Reading page one draft')
  const image = await originalImage(page, id)
  const reading = await send(page, 'Explain the claim on this page')
  await sentSource(page, 1, 1, 'read', image)
  expect(reading.conversationId).not.toBe(ordinary.conversationId)
  const all = await savedConversations(page)
  expect(all.find(item => item.id === ordinary.conversationId)?.messages.some(message => message.content === 'Explain the claim on this page')).toBe(false)
  expect(all.find(item => item.id === reading.conversationId)?.messages.some(message => message.content.includes('Ordinary Chat draft'))).toBe(false)
  await capture(page, info, 'shared-chat-reading-desktop.png')
  await jumpToPage(page, 2)
  await expect(page.getByText('材料草稿保存在此设备', { exact: true })).toBeVisible()
  await page.reload()
  await expectSharedChat(page)
  await expect(editor(page)).toHaveText('Reading page two draft')
  await jumpToPage(page, 1)
  await expect(messages(page)).toContainText('Simulated shared Chat reply')
})


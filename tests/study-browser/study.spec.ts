test('attachment failures preserve the common draft, provider failures retry the exact stored source', async ({ page }) => {
  const id = await importMaterial(page, material())
  const image = await originalImage(page, id)
  await page.evaluate(() => { window.__studyTest.failAttachmentNext = true })
  await editor(page).fill('Keep this question if saving the source fails')
  await sendButton(page).click()
  await expect(messages(page)).toContainText('Simulated attachment storage full')
  await expect(editor(page)).toHaveText('Keep this question if saving the source fails')
  expect(await page.evaluate(() => window.__studyTest.requests)).toHaveLength(0)
  await page.evaluate(() => { window.__studyTest.failNext = true })
  await sendButton(page).click()
  await expect(messages(page)).toContainText('Simulated provider unavailable')
  await expect(editor(page)).toHaveText('')
  const failed = await sentSource(page, 0, 1, 'read', image)
  await page.getByRole('button', { name: '重试', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__studyTest.requests.length)).toBe(2)
  const retried = await sentSource(page, 1, 1, 'read', image)
  expect(retried.kind).toBe('retry')
  expect(retried.attachments).toEqual(failed.attachments)
  expect(retried.studySource).toEqual(failed.studySource)
  await expect.poll(async () => (await savedConversations(page)).find(item => item.id === failed.conversationId)?.messages.at(-1)?.stream_outcome).toBe('completed')
  expect(await page.evaluate(() => window.__studyTest.savedImages.length)).toBe(1)
})


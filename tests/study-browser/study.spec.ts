test('all legacy outcomes migrate once into Chat while original backup and missing-image limits remain', async ({ page }) => {
  const materialId = await importMaterial(page, material())
  await expect(page.getByText('材料草稿保存在此设备', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Normal Chat', exact: true }).click()
  await expect(composer(page)).toHaveCount(0)
  const originalBackup = await page.evaluate(id => new Promise<string>((resolve, reject) => {
    const open = indexedDB.open('kivio-study')
    open.onerror = () => reject(open.error)
    open.onsuccess = () => {
      const db = open.result
      const tx = db.transaction(['documents', 'meta'], 'readwrite')
      let archive = ''
      tx.onerror = () => { db.close(); reject(tx.error) }
      tx.oncomplete = () => { db.close(); localStorage.setItem('kivio-chat-dev-conversations', '[]'); resolve(archive) }
      const documents = tx.objectStore('documents'), meta = tx.objectStore('meta')
      const get = documents.get(id)
      get.onsuccess = () => {
        const record = get.result, previousBytes = record.metadataBytes
        record.document.pages['1'] = { question: 'Legacy unsent draft', attempt: 'Legacy optional thought', correctedText: 'ARCHIVED_MANUAL_TEXT_NOT_SENT', notes: 'Legacy note retained', region: null,
          history: ['complete', 'error', 'cancelled', 'interrupted', 'streaming'].map((status, index) => ({ id: `legacy-${status}`, mode: 'read', question: `Legacy ${status} question`, attempt: '', sourceText: 'ARCHIVED_EXTRACTED_TEXT_NOT_SENT', sourceImageUsed: true, region: null, answer: `Legacy ${status} answer`, status, ...(status === 'error' ? { error: 'Legacy provider failure' } : {}), createdAt: index + 1, providerId: 'study-fixture', model: 'test-vision', page: 1 })) }
        archive = JSON.stringify(record.document.pages['1'])
        record.metadataBytes = new TextEncoder().encode(JSON.stringify(record.document)).byteLength
        documents.put(record); meta.delete(`chat:${id}:1`)
        const workspace = meta.get('workspace')
        workspace.onsuccess = () => meta.put({ ...workspace.result, totalBytes: workspace.result.totalBytes - previousBytes + record.metadataBytes })
      }
    }
  }), materialId)
  // This is a pre-upgrade startup snapshot. A hash-only goto keeps the already
  // loaded Study and composer stores alive, so reload the normal route first.
  await page.reload()
  await openStudy(page)
  await expectSharedChat(page)
  await expect(editor(page)).toHaveText('Legacy unsent draft')
  const conversationId = `conv_study_${materialId}_1`
  const migrated = (await savedConversations(page)).find(item => item.id === conversationId)!
  expect(migrated.messages).toHaveLength(10)
  expect(migrated.messages.filter(message => message.role === 'assistant').map(message => message.stream_outcome)).toEqual(['completed', 'error', 'cancelled', 'interrupted', 'interrupted'])
  expect(migrated.messages.find(message => message.content === 'Legacy error answer')?.study_legacy_error).toBe('Legacy provider failure')
  expect(JSON.stringify(migrated)).not.toContain('ARCHIVED_')
  await expect(messages(page)).toContainText('旧记录未保存原图')
  await page.reload(); await expectSharedChat(page)
  expect((await savedConversations(page)).find(item => item.id === conversationId)?.messages).toHaveLength(10)
  const backup = await page.evaluate(id => new Promise<string>((resolve, reject) => {
    const open = indexedDB.open('kivio-study'); open.onerror = () => reject(open.error)
    open.onsuccess = () => { const db = open.result; const get = db.transaction('documents').objectStore('documents').get(id); get.onsuccess = () => { db.close(); resolve(JSON.stringify(get.result.document.pages['1'])) } }
  }), materialId)
  expect(backup).toBe(originalBackup)
  expect(await page.evaluate(() => window.__studyTest.requests)).toHaveLength(0)
  // A durable migration receipt must not silently resurrect a removed Chat.
  await page.evaluate(id => { const saved = JSON.parse(localStorage.getItem('kivio-chat-dev-conversations') ?? '[]'); localStorage.setItem('kivio-chat-dev-conversations', JSON.stringify(saved.filter((item: { id: string }) => item.id !== id))) }, conversationId)
  await page.reload()
  await expect(page.locator('.kv-study [role="alert"]')).toContainText('Could not reopen the saved Study conversation')
  expect((await savedConversations(page)).some(item => item.id === conversationId)).toBe(false)
})
